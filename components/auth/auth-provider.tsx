"use client";

import { useRouter } from "next/navigation";
import * as React from "react";
import type { User } from "@supabase/supabase-js";

import { getMe, updateMe } from "@/lib/api/users";
import { supabaseConfigured } from "@/lib/env";
import { seedPrefs, setPrefsPusher } from "@/lib/local-prefs";
import { getBrowserSupabase } from "@/lib/supabase/browser";
import type { UserProfile } from "@/lib/types";
import { isAutoGeneratedUsername } from "@/lib/username";

type SessionState = {
  /** The Supabase auth user, null when signed out (or still resolving). */
  user: User | null;
  /** The Klyvi profile row (username, bio). Null until it loads. */
  profile: UserProfile | null;
  /** True until the first getSession resolves; gates flicker, not routing. */
  loading: boolean;
  /** True when the profile failed to load. Settings shows a retry for it. */
  profileFailed: boolean;
  /** Load the profile again after a failure. */
  reloadProfile: () => void;
  /** Push a fresh profile in after Settings saves, so greetings update. */
  setProfile: (p: UserProfile) => void;
  signOut: () => Promise<void>;
};

const SessionContext = React.createContext<SessionState>({
  user: null,
  profile: null,
  loading: true,
  profileFailed: false,
  reloadProfile: () => {},
  setProfile: () => {},
  signOut: async () => {},
});

/**
 * Owns the browser auth state and the Klyvi profile that hangs off it, so
 * any screen can greet by name without refetching. The profile is fetched
 * once per signed-in user, and saves hand back the new row, so nothing else
 * needs to read /users/me. Routing decisions live
 * in proxy.ts; this context only answers who is signed in.
 */
export function AuthProvider({ children }: { children: React.ReactNode }) {
  const router = useRouter();
  const [user, setUser] = React.useState<User | null>(null);
  // The profile is tagged with the user it belongs to, so signing out (or in
  // as someone else) hides a stale one without an effect clearing it.
  const [owned, setOwned] = React.useState<{
    userId: string;
    profile: UserProfile;
  } | null>(null);
  const profile = user && owned?.userId === user.id ? owned.profile : null;
  const userId = user?.id ?? null;
  const [failedFor, setFailedFor] = React.useState<string | null>(null);
  const profileFailed = userId != null && failedFor === userId && !profile;
  const [attempt, setAttempt] = React.useState(0);
  // The latest user object, for the sign-up username claim below. The effect
  // that reads it is keyed on the id alone.
  const userRef = React.useRef(user);
  React.useEffect(() => {
    userRef.current = user;
  }, [user]);
  // Without Supabase there is no session to wait for.
  const [loading, setLoading] = React.useState(supabaseConfigured);

  React.useEffect(() => {
    const sb = getBrowserSupabase();
    if (!sb) return;
    let cancelled = false;

    sb.auth.getSession().then(({ data }) => {
      if (cancelled) return;
      setUser(data.session?.user ?? null);
      setLoading(false);
    });

    const {
      data: { subscription },
    } = sb.auth.onAuthStateChange((_event, session) => {
      if (cancelled) return;
      setUser(session?.user ?? null);
      setLoading(false);
    });

    return () => {
      cancelled = true;
      subscription.unsubscribe();
    };
  }, []);

  // Load the Klyvi profile, and claim the username chosen at sign-up.
  //
  // The claim cannot happen on the sign-up form: there is no session yet, so
  // there is nothing to authenticate a write with. The API also auto-creates
  // the row as user_<8 hex> on the first authenticated request, so the
  // desired name is applied here, once, and only while the row still carries
  // that placeholder. A collision leaves the placeholder in place; Settings
  // is where it gets resolved.
  //
  // Keyed on the id, not the user object. Supabase hands over a new object
  // at every token refresh and tab focus, which once meant 18 reads of
  // /users/me in a few minutes of browsing.
  React.useEffect(() => {
    if (!userId) return;
    let cancelled = false;

    (async () => {
      let me: UserProfile;
      try {
        me = await getMe();
      } catch {
        if (!cancelled) setFailedFor(userId);
        return;
      }

      const desired = userRef.current?.user_metadata?.username;
      if (
        typeof desired === "string" &&
        desired.length > 0 &&
        isAutoGeneratedUsername(me.username)
      ) {
        try {
          me = await updateMe({ username: desired });
        } catch {
          // Taken, or the write failed. Keep the placeholder rather than
          // blocking sign-in over a display name.
        }
        // Clear the request either way so it is attempted once, not on
        // every page load for the life of the account.
        const sb = getBrowserSupabase();
        await sb?.auth.updateUser({ data: { username: null } }).catch(() => {});
      }

      if (cancelled) return;
      setOwned({ userId, profile: me });
      // Adopt the server's settings blob, then let later changes push back
      // (debounced). Order matters: seed first so the pusher does not fire
      // on the values we just received.
      seedPrefs(me.settings);
      setPrefsPusher((settings) => {
        updateMe({ settings }).catch(() => {});
      });
    })();

    return () => {
      cancelled = true;
    };
  }, [userId, attempt]);

  const reloadProfile = React.useCallback(() => {
    setFailedFor(null);
    setAttempt((n) => n + 1);
  }, []);

  // Stop pushing prefs once signed out.
  React.useEffect(() => {
    if (!user) setPrefsPusher(null);
  }, [user]);

  const signOut = React.useCallback(async () => {
    const sb = getBrowserSupabase();
    if (!sb) return;
    await sb.auth.signOut();
    // The proxy sees the cleared cookie on the next navigation; go somewhere
    // public so the user does not land on a redirect.
    router.push("/");
    router.refresh();
  }, [router]);

  const setProfile = React.useCallback(
    (p: UserProfile) => {
      if (user) setOwned({ userId: user.id, profile: p });
    },
    [user]
  );

  const value = React.useMemo(
    () => ({
      user,
      profile,
      loading,
      profileFailed,
      reloadProfile,
      setProfile,
      signOut,
    }),
    [user, profile, loading, profileFailed, reloadProfile, setProfile, signOut]
  );

  return (
    <SessionContext.Provider value={value}>{children}</SessionContext.Provider>
  );
}

export function useSession(): SessionState {
  return React.useContext(SessionContext);
}

import { outLabel } from "@/lib/release";
import type { LibraryEntry, Reason, Scored, TrackingStatus } from "@/lib/types";
import { isAutoGeneratedUsername } from "@/lib/username";

/** How many of the top picks the hero takes turns with. */
export const HERO_POOL = 4;

/**
 * The name the greeting uses: the first name from the account's display
 * name, else a username the person chose. Never the handle Klyvi generated
 * at sign-up ("user_3f9a0c12"), which reads as a bug in a greeting.
 */
export function greetingName(
  profile: { username: string } | null,
  meta: Record<string, unknown> | null | undefined
): string | null {
  const display = meta?.full_name ?? meta?.name;
  if (typeof display === "string" && display.trim()) {
    return display.trim().split(/\s+/)[0];
  }
  const username = profile?.username?.trim();
  if (!username || isAutoGeneratedUsername(username)) return null;
  return username;
}

/** Which of the top picks leads on this visit: one along each time. */
export function heroStart(turn: number, picks: number): number {
  const pool = Math.min(HERO_POOL, picks);
  return pool > 0 ? turn % pool : 0;
}

export type ReasonRail = { key: string; title: string; picks: Scored[] };

/**
 * Rows of picks that share a title they were picked because of ("Because
 * you liked The Dark Knight"), biggest first. A reason with fewer than `min`
 * picks makes a thin row, so it stays in Top picks only.
 */
export function reasonRails(
  picks: Scored[],
  { min = 4, max = 3 }: { min?: number; max?: number } = {}
): ReasonRail[] {
  const groups = new Map<number, { name: string; picks: Scored[] }>();
  for (const p of picks) {
    for (const r of p.reasons) {
      if (r.kind !== "because" || !r.name) continue;
      const g = groups.get(r.id);
      if (g) g.picks.push(p);
      else groups.set(r.id, { name: r.name, picks: [p] });
    }
  }
  return [...groups.entries()]
    .filter(([, g]) => g.picks.length >= min)
    .sort((a, b) => b[1].picks.length - a[1].picks.length)
    .slice(0, max)
    .map(([id, g]) => ({
      key: `because-${id}`,
      title: `Because you liked ${g.name}`,
      picks: g.picks,
    }));
}

/**
 * The keywords that recur across the picks: a glimpse of what Klyvi has
 * learned. Genres stay out (#18), since they say nothing a shelf label
 * doesn't. One mention is noise, so a keyword needs two.
 */
export function tasteKeywords(picks: Scored[], max = 6): Reason[] {
  const seen = new Map<number, { reason: Reason; count: number }>();
  for (const p of picks) {
    for (const r of p.reasons) {
      if (r.kind !== "keyword" || !r.name) continue;
      const cur = seen.get(r.id);
      if (cur) cur.count++;
      else seen.set(r.id, { reason: r, count: 1 });
    }
  }
  return [...seen.values()]
    .filter((x) => x.count >= 2)
    .sort((a, b) => b.count - a.count)
    .slice(0, max)
    .map((x) => x.reason);
}

/** Planned titles that are not out yet, soonest first, with their day. */
export function comingUp(
  entries: LibraryEntry[],
  now: Date = new Date()
): { entry: LibraryEntry; label: string }[] {
  return entries
    .filter((e) => e.status === "planning")
    .flatMap((e) => {
      const label = outLabel(e.releaseDate, now);
      return label ? [{ entry: e, label }] : [];
    })
    .sort((a, b) => a.entry.releaseDate!.localeCompare(b.entry.releaseDate!));
}

const LEADS: Record<TrackingStatus, [string, string]> = {
  watching: ["You started", ""],
  planning: ["You added", "to your watchlist"],
  completed: ["You finished", ""],
  rewatching: ["You started rewatching", ""],
  paused: ["You paused", ""],
  dropped: ["You dropped", ""],
};

/**
 * One activity line, around the title: "You rated Parasite 95", or what
 * changed when there is no score. The score stays a number so the line can
 * show it in the scoring system from Settings.
 */
export function activityLine(e: LibraryEntry): {
  lead: string;
  tail: string;
  score: number | null;
} {
  if (e.score != null) return { lead: "You rated", tail: "", score: e.score };
  const [lead, tail] = LEADS[e.status];
  return { lead, tail, score: null };
}
